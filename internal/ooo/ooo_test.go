// --- explicit timezone: dates/times mean YOUR timezone, wherever the daemon runs ---

func TestActive_TimezoneInterpretsFromInThatZone(t *testing.T) {
	// 11:00 Zurich (CEST, UTC+2) == 09:00 UTC
	cfg := config.OOOConfig{Enabled: true, Body: "away", From: "2026-08-31 11:00", Timezone: "Europe/Zurich"}
	before := time.Date(2026, 8, 31, 8, 59, 0, 0, time.UTC)
	after := time.Date(2026, 8, 31, 9, 1, 0, 0, time.UTC)
	if Active(cfg, before) {
		t.Fatal("08:59 UTC is before 11:00 Zurich — must be inactive")
	}
	if !Active(cfg, after) {
		t.Fatal("09:01 UTC is after 11:00 Zurich — must be active")
	}
}


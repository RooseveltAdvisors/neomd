// --- Reply message construction ---

func TestBuildReply_LooksLikeNormalNeomdMailPlusAutoHeaders(t *testing.T) {
	orig := imap.Email{
		From:       "Alice <alice@example.com>",
		Subject:    "project question",
		MessageID:  "<orig-id@example.com>",
		References: "<root-id@example.com>",
	}
	raw, err := BuildReply("Me <me@ssp.sh>", "alice@example.com", "Out of Office", "I'm **away**.", "", orig)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"Auto-Submitted: auto-replied",
		"X-Auto-Response-Suppress: All",
		"In-Reply-To: <orig-id@example.com>",
		"References: <root-id@example.com> <orig-id@example.com>",
		"To: alice@example.com",
		"Subject: Out of Office",
		"multipart/alternative", // same MIME shape as a composed neomd email
		"text/html",
	} {
		if !bytes.Contains(raw, []byte(want)) {
			t.Fatalf("built reply missing %q\n---\n%s", want, raw)
		}
	}
	if bytes.Contains(raw, []byte("Cc:")) {
		t.Fatal("OOO reply must never carry a Cc header")
	}
}

// --- Reply-once cache ---

func TestCache_MarkAndHasRepliedPersists(t *testing.T) {
	path := filepath.Join(t.TempDir(), "ooo_replied")
	c, err := LoadCache(path, "2026-09-07")
	if err != nil {
		t.Fatal(err)
	}
	if c.HasReplied("alice@example.com") {
		t.Fatal("fresh cache must be empty")
	}
	if err := c.MarkReplied("alice@example.com"); err != nil {
		t.Fatal(err)
	}
	if !c.HasReplied("alice@example.com") {
		t.Fatal("MarkReplied must be visible immediately")
	}
	// reload — must persist
	c2, err := LoadCache(path, "2026-09-07")
	if err != nil {
		t.Fatal(err)
	}
	if !c2.HasReplied("alice@example.com") {
		t.Fatal("MarkReplied must persist across reloads")
	}
}

func TestCache_PeriodChangeResets(t *testing.T) {
	path := filepath.Join(t.TempDir(), "ooo_replied")
	c, err := LoadCache(path, "2026-09-07")
	if err != nil {
		t.Fatal(err)
	}
	if err := c.MarkReplied("alice@example.com"); err != nil {
		t.Fatal(err)
	}
	// new vacation period → everyone may get a fresh reply
	c2, err := LoadCache(path, "2026-12-24")
	if err != nil {
		t.Fatal(err)
	}
	if c2.HasReplied("alice@example.com") {
		t.Fatal("changing the OOO period must reset the replied cache")
	}
}

func TestCache_StartedPersistsAcrossReloads(t *testing.T) {
	path := filepath.Join(t.TempDir(), "ooo_replied")
	c, err := LoadCache(path, "open")
	if err != nil {
		t.Fatal(err)
	}
	if !c.Started().IsZero() {
		t.Fatal("fresh cache must have zero start")
	}
	start := time.Date(2026, 8, 31, 8, 0, 0, 0, time.UTC)
	if err := c.SetStarted(start); err != nil {
		t.Fatal(err)
	}
	c2, err := LoadCache(path, "open")
	if err != nil {
		t.Fatal(err)
	}
	if !c2.Started().Equal(start) {
		t.Fatalf("started = %v, want %v", c2.Started(), start)
	}
}

// --- Candidate selection (daemon decision logic) ---

func TestShouldConsider(t *testing.T) {
	started := time.Date(2026, 8, 31, 8, 0, 0, 0, time.UTC)
	own := map[string]bool{"me@ssp.sh": true}
	screenedIn := func(a string) bool { return a == "alice@example.com" }
	replied := func(a string) bool { return a == "bob@example.com" }

	mk := func(from string, when time.Time) imap.Email {
		return imap.Email{From: from, Date: when}
	}
	after := started.Add(time.Hour)

	cases := []struct {
		name     string
		e        imap.Email
		wantAddr string
		wantOK   bool
	}{
		{"screened-in sender after start", mk("Alice <alice@example.com>", after), "alice@example.com", true},
		{"not screened in", mk("stranger@example.com", after), "", false},
		{"own address never gets a reply", mk("me@ssp.sh", after), "", false},
		{"arrived before OOO started", mk("alice@example.com", started.Add(-time.Hour)), "", false},
		{"unparseable sender", mk("", after), "", false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			addr, ok := ShouldConsider(c.e, started, own, screenedIn, replied)
			if addr != c.wantAddr || ok != c.wantOK {
				t.Fatalf("got (%q, %v), want (%q, %v)", addr, ok, c.wantAddr, c.wantOK)
			}
		})
	}

	// already-replied is checked via the replied func
	addr, ok := ShouldConsider(mk("bob@example.com", after), started, own, func(string) bool { return true }, replied)
	if ok {
		t.Fatalf("already-replied sender must be skipped, got (%q, %v)", addr, ok)
	}
}


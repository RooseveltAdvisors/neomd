// --- Auto-generated mail detection (loop protection) ---

func rawWith(headers string) []byte {
	return []byte("From: a@example.com\r\n" + headers + "Subject: hi\r\n\r\nbody\r\n")
}

func TestIsAutoGenerated(t *testing.T) {
	cases := []struct {
		name    string
		raw     []byte
		autoGen bool
	}{
		{"plain mail", rawWith(""), false},
		{"auto-submitted auto-replied", rawWith("Auto-Submitted: auto-replied\r\n"), true},
		{"auto-submitted auto-generated", rawWith("Auto-Submitted: auto-generated\r\n"), true},
		{"auto-submitted no", rawWith("Auto-Submitted: no\r\n"), false},
		{"precedence bulk", rawWith("Precedence: bulk\r\n"), true},
		{"precedence junk", rawWith("Precedence: junk\r\n"), true},
		{"precedence list", rawWith("Precedence: list\r\n"), true},
		{"list-id header", rawWith("List-Id: <dev.lists.example.com>\r\n"), true},
		{"x-auto-response-suppress", rawWith("X-Auto-Response-Suppress: All\r\n"), true},
		{"x-autoreply", rawWith("X-Autoreply: yes\r\n"), true},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := IsAutoGenerated(c.raw); got != c.autoGen {
				t.Fatalf("IsAutoGenerated = %v, want %v", got, c.autoGen)
			}
		})
	}
}

